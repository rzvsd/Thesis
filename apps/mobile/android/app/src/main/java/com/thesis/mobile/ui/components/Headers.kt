/*
 * Headers (docs/app-redesign/DESIGN-DIRECTION.md, section 3 #5, #6, #7, #39). Titles are headings for TalkBack.
 * Section headlines are sentences about the result, generated by the screen from data; the kicker is the category.
 */

/**
 * A lede with its lead clause: the lead in Newsreader 600 `ink`, the rest in `ink2` (Deep Dive verdict line).
 */
fun ledeText(lead: String, rest: String?, p: ThesisPalette): AnnotatedString = buildAnnotatedString {
    withStyle(SpanStyle(fontWeight = ThesisType.lead.fontWeight, color = p.ink)) { append(lead) }
    if (!rest.isNullOrBlank()) {
        append(" ")
        withStyle(SpanStyle(color = p.ink2)) { append(rest) }
    }
}

/**
 * The one screen title block (#5): optional [eyebrow], the serif [title] (`title`, capped at 1.3x; Home passes
 * [compact] = true for `headline`, also capped at 1.3x, max 2 lines), an optional [deck] (`lede`, ink2) and a [meta] caption with a
 * [LoadingHairline] while [refreshing]. The top bar shows [title] once this block has scrolled away.
 */
@Composable
fun ScreenHeader(
    title: String,
    modifier: Modifier = Modifier,
    eyebrow: String? = null,
    deck: String? = null,
    meta: String? = null,
    refreshing: Boolean = false,
    compact: Boolean = false,
) {
    val p = LocalThesisPalette.current
    Column(modifier.fillMaxWidth()) {
        if (eyebrow != null) {
            Eyebrow(eyebrow)
            Spacer(Modifier.height(ThesisSpace.s))
        }
        Text(
            title,
            modifier = Modifier.semantics { heading() },
            // Both are capped at 1.3x, so Home's compact headline never outgrows the other tabs' titles at 2.0x.
            style = ThesisType.capped(if (compact) ThesisType.headline else ThesisType.title),
            color = p.ink,
            maxLines = if (compact) 2 else Int.MAX_VALUE,
            overflow = TextOverflow.Ellipsis,
        )
        if (deck != null) {
            Spacer(Modifier.height(ThesisSpace.s))
            Text(deck, style = ThesisType.lede, color = p.ink2)
        }
        if (meta != null || refreshing) {
            Spacer(Modifier.height(ThesisSpace.m))
            if (meta != null) Text(meta, style = ThesisType.caption, color = p.muted)
            Spacer(Modifier.height(ThesisSpace.xs))
            LoadingHairline(active = refreshing)
        }
    }
}

/**
 * Section header (#6): [kicker] (accent caps) over a serif [headline] that states the result ("2 of your names need
 * a review"), an optional [deck], and an optional trailing text action ("All names") on the headline's baseline.
 */
@Composable
fun SectionHeader(
    kicker: String,
    headline: String,
    modifier: Modifier = Modifier,
    deck: String? = null,
    actionLabel: String? = null,
    onAction: (() -> Unit)? = null,
) {
    val p = LocalThesisPalette.current
    val action = if (actionLabel != null && onAction != null) actionLabel to onAction else null
    // At large font sizes the action beside the headline squeezes it into a narrow column of short lines: the
    // action moves under the headline instead (A4).
    val stacked = action != null && LocalDensity.current.fontScale >= STACK_ACTION_FONT_SCALE
    Column(modifier.fillMaxWidth()) {
        Kicker(kicker)
        Spacer(Modifier.height(ThesisSpace.xs))
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(ThesisSpace.m)) {
            Text(
                headline,
                modifier = Modifier
                    .weight(1f)
                    .alignByBaseline()
                    .semantics { heading() },
                style = ThesisType.capped(ThesisType.headline),
                color = p.ink,
            )
            if (action != null && !stacked) {
                TextAction(action.first, action.second, Modifier.alignByBaseline(), trailing = true)
            }
        }
        if (action != null && stacked) {
            Spacer(Modifier.height(ThesisSpace.xs))
            TextAction(action.first, action.second, trailing = true)
        }
        if (deck != null) {
            Spacer(Modifier.height(ThesisSpace.xs))
            Text(deck, style = ThesisType.bodySmall, color = p.ink2)
        }
    }
}

/** From this font scale up, [SectionHeader]'s action sits under the headline rather than beside it. */
private const val STACK_ACTION_FONT_SCALE = 1.5f

/** A badge in a chapter header's kicker row. */
@Immutable
data class BadgeSpec(val text: String, val tone: Tone)

/**
 * Chapter header (#7), the Deep Dive chapter anatomy: gold italic [numeral] ("01") with the [label] kicker, then
 * [badges] and the [source] caption, all wrapping; then the [title] and a [lede] whose lead clause is 600 ink
 * (build it with [ledeText]). [small] uses `headline` instead of `title` (app-screen chapters).
 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
fun ChapterHeader(
    numeral: Int,
    label: String,
    title: String,
    modifier: Modifier = Modifier,
    lede: AnnotatedString? = null,
    badges: List<BadgeSpec> = emptyList(),
    source: String? = null,
    small: Boolean = false,
) {
    val p = LocalThesisPalette.current
    Column(modifier.fillMaxWidth(), verticalArrangement = Arrangement.spacedBy(ThesisSpace.m)) {
        FlowRow(
            horizontalArrangement = Arrangement.spacedBy(Kit.chipGap),
            verticalArrangement = Arrangement.spacedBy(Kit.chipGap),
        ) {
            Row(
                Modifier
                    .align(Alignment.Bottom)
                    .padding(end = ThesisSpace.xs),
                horizontalArrangement = Arrangement.spacedBy(ThesisSpace.m),
            ) {
                Text(
                    numeral.toString().padStart(2, '0'),
                    modifier = Modifier.alignByBaseline(),
                    style = ThesisType.capped(ThesisType.numeral),
                    color = p.accent,
                )
                Kicker(label, Modifier.alignByBaseline())
            }
            badges.forEach { StatusBadge(it.text, it.tone, Modifier.align(Alignment.CenterVertically)) }
            if (source != null) {
                Text(
                    source,
                    modifier = Modifier.align(Alignment.CenterVertically),
                    style = ThesisType.caption,
                    color = p.muted,
                )
            }
        }
        Text(
            title,
            modifier = Modifier.semantics { heading() },
            style = ThesisType.capped(if (small) ThesisType.headline else ThesisType.title),
            color = p.ink,
        )
        if (lede != null) Text(lede, style = ThesisType.lede, color = p.ink2)
    }
}

/**
 * Sticky day header for History and Inbox (#39): eyebrow text ("TODAY", "MON 17 NOV") on the bar background with a
 * bottom hairline. Use it as a `stickyHeader`.
 */
@Composable
fun DayHeader(text: String, modifier: Modifier = Modifier) {
    Eyebrow(
        text,
        modifier
            .fillMaxWidth()
            .barBackground(BarHairline.Bottom)
            .padding(horizontal = ThesisSpace.gutter, vertical = ThesisSpace.s)
            .semantics { heading() },
    )
}
