export function drawChipGrid(
  commands: string[],
  x: number,
  top: number,
  width: number,
  chips: ReportChip[],
): void {
  const columnWidth = (width - 10) / 2;
  chips.forEach((chip, index) => {
    const column = index % 2;
    const row = Math.floor(index / 2);
    drawStatusChip(
      commands,
      x + column * (columnWidth + 10),
      top + row * 30,
      columnWidth,
      chip.label,
      chip.tone,
    );
  });
}

export function drawChipRow(
  commands: string[],
  x: number,
  top: number,
  width: number,
  chips: ReportChip[],
): void {
  const visible = chips.slice(0, 3);
  const chipWidth = (width - 20) / Math.max(visible.length, 1);
  visible.forEach((chip, index) => {
    drawStatusChip(commands, x + index * (chipWidth + 10), top, chipWidth, chip.label, chip.tone);
  });
}

export function drawStatusChip(
  commands: string[],
  x: number,
  top: number,
  width: number,
  label: string,
  tone: PdfTone,
): void {
  const palette = tonePalette(tone);
  drawPanel(commands, x, top, width, 22, {
    fill: palette.fill,
    stroke: palette.stroke,
    lineWidth: 0.6,
  });
  const parts = label.split(": ");
  if (parts.length === 2) {
    const eyebrow = parts[0] ?? label;
    const value = parts[1] ?? "";
    drawText(commands, x + width / 2, top + 4, eyebrow, {
      font: "bodyBold",
      size: 6.5,
      color: palette.text,
      align: "center",
    });
    drawText(commands, x + width / 2, top + 11, value, {
      font: "bodyBold",
      size: 8,
      color: palette.text,
      align: "center",
    });
    return;
  }
  drawText(commands, x + width / 2, top + 7, label, {
    font: "bodyBold",
    size: 8.5,
    color: palette.text,
    align: "center",
  });
}

export function drawMetricTileStrip(
  commands: string[],
  x: number,
  top: number,
  width: number,
  tiles: MetricTile[],
): void {
  const visible = tiles.slice(0, 4);
  if (visible.length === 0) {
    return;
  }
  const tileWidth = (width - 12 * (visible.length - 1)) / visible.length;
  visible.forEach((tile, index) => {
    drawMetricTile(commands, x + index * (tileWidth + 12), top, tileWidth, tile);
  });
}

export function drawMetricTile(
  commands: string[],
  x: number,
  top: number,
  width: number,
  tile: MetricTile,
): void {
  const palette = tonePalette(tile.tone);
  drawPanel(commands, x, top, width, 44, {
    fill: tile.tone === "neutral" ? white : palette.softFill,
    stroke: divider,
    lineWidth: 0.8,
  });
  drawText(commands, x + 12, top + 12, tile.label, {
    font: "bodyBold",
    size: 8.5,
    color: tile.tone === "neutral" ? muted : palette.stroke,
  });
  drawText(commands, x + 12, top + 29, tile.value, {
    font: "bodyBold",
    size: 11,
    color: charcoal,
  });
}

