export interface MarketPulsePdf {
  bytes: Uint8Array;
  pageCount: number;
}

const bodyStyle: TextStyle = { size: 10, font: "body", color: ink };
const leadStyle: TextStyle = { size: 11, font: "body", color: charcoal, leading: 1.5 };
const kickerStyle: TextStyle = { size: 9.5, font: "body", color: muted };
const smallStyle: TextStyle = { size: 8.5, font: "body", color: muted };
const strongStyle: TextStyle = { size: 10, font: "bodyBold", color: charcoal };

export function buildMarketPulsePdf(report: MarketPulseReport): MarketPulsePdf {
  const plan = buildPulseBriefPlan(report);
  const factPack = plan.fact_pack;
  const copy = plan.copy;
  const layout = new FlowLayout();

  drawHeader(layout, report, factPack, copy);
  if (factPack.mode === "quiet") {
    drawLead(layout, copy, true);
    drawTape(layout, report, factPack, copy, true);
    layout.heading("Nothing Moved The Needle");
    layout.paragraph(copy.what_changed_summary, leadStyle);
  } else {
    drawLead(layout, copy, false);
    drawTape(layout, report, factPack, copy, false);
    drawOneThing(layout, copy);
    drawDeltas(layout, factPack, copy);
    drawYourNames(layout, factPack, copy);
    drawCalendarAndHeadlines(layout, factPack, copy);
    layout.heading("The Honest Read");
    layout.paragraph(copy.smart_comment, { ...bodyStyle, size: 9.5 });
  }
  drawSources(layout, factPack);

  const dateLabel = formatDate(report.cycle_end || report.generated_at);
  const pages = layout.toPdfPages({ dateLabel, footerLabel: "Generated by Thesis | Market Pulse" });
  return { bytes: renderSimplePdf(pages), pageCount: pages.length };
}

function drawHeader(
  layout: FlowLayout,
  report: MarketPulseReport,
  factPack: PulseBriefFactPack,
  copy: PulseBriefCopy,
): void {
  layout.gap(6);
  layout.textAt(left, layout.y, "THESIS", { size: 24, font: "display", color: charcoal, tracking: 2 });
  layout.textAt(right, layout.y + 4, formatDate(report.cycle_end || report.generated_at), {
    size: 10,
    font: "bodyBold",
    color: gold,
    tracking: 0.8,
  }, "right");
  layout.gap(30);
  layout.textAt(left, layout.y, "MORNING BRIEF", { size: 9, font: "bodyBold", color: gold, tracking: 1.4 });
  layout.gap(16);
  layout.line(left, layout.y, right, layout.y, gold, 1.2);
  layout.gap(12);
  layout.paragraph(copy.the_read, { size: 13, font: "display", color: charcoal, leading: 1.4 });
  layout.gap(4);
  layout.textAt(left, layout.y, modeLabel(factPack).toUpperCase(), { ...smallStyle, tracking: 0.6 });
  layout.gap(16);
}

function drawLead(layout: FlowLayout, copy: PulseBriefCopy, compact: boolean): void {
  layout.heading("The Read");
  const style = compact ? { ...leadStyle, size: 10.5 } : leadStyle;
  splitParagraphs(copy.morning_story).forEach((paragraph, index) => {
    if (index > 0) layout.gap(7);
    layout.paragraph(paragraph, style);
  });
}

function drawTape(
  layout: FlowLayout,
  report: MarketPulseReport,
  factPack: PulseBriefFactPack,
  copy: PulseBriefCopy,
  compact: boolean,
): void {
  const moves = [...factPack.tape.indices, ...factPack.tape.cross_asset]
    .filter((move) => typeof move.changePct === "number" || typeof move.change === "number")
    .sort((a, b) => moveDisplayRank(a) - moveDisplayRank(b))
    .slice(0, compact ? 6 : 8);

  layout.heading(tapeHeading(factPack, copy), 60);
  if (moves.length > 0) {
    drawMoveGrid(layout, moves);
  } else {
    layout.paragraph("Market tape values were not available in the approved path.", kickerStyle);
  }
  layout.gap(4);
  layout.paragraph(copy.tape_narrative, kickerStyle);
  if (!compact) {
    drawSectorStrip(layout, report);
    drawSparklines(layout, report);
  }
  layout.gap(6);
  layout.paragraph(copy.tape_color, { size: 11, font: "display", color: charcoal });
}

function drawMoveGrid(layout: FlowLayout, moves: PulseBriefMove[]): void {
  const columns = 4;
  const gapX = 7;
  const cellWidth = (width - gapX * (columns - 1)) / columns;
  const cellHeight = 40;
  for (let start = 0; start < moves.length; start += columns) {
    layout.ensure(cellHeight + 7);
    moves.slice(start, start + columns).forEach((move, index) => {
      const x = left + index * (cellWidth + gapX);
      layout.rect(x, layout.y, cellWidth, cellHeight, panelIvory, divider, 0.6);
      layout.textAt(x + 8, layout.y + 8, fitText(move.label, cellWidth - 16, 8, "body"), smallStyle);
      layout.textAt(x + 8, layout.y + 21, formatMove(move), {
        size: 12,
        font: "bodyBold",
        color: toneColor(moveTone(move)),
      });
    });
    layout.y += cellHeight + 7;
  }
}

function drawSectorStrip(layout: FlowLayout, report: MarketPulseReport): void {
  const leadership = report.market_tape?.sector_leadership;
  const sectors = dedupeMoves([...(leadership?.leaders ?? []), ...(leadership?.laggards ?? [])]).slice(0, 10);
  if (sectors.length === 0) {
    return;
  }
  layout.gap(6);
  layout.subheading("Sector leadership");
  const columns = 5;
  const gapX = 6;
  const cellWidth = (width - gapX * (columns - 1)) / columns;
  const cellHeight = 30;
  for (let start = 0; start < sectors.length; start += columns) {
    layout.ensure(cellHeight + 6);
    sectors.slice(start, start + columns).forEach((sector: Loose, index: number) => {
      const change: number = sector.daily_change_pct ?? 0;
      const x = left + index * (cellWidth + gapX);
      const intensity = Math.min(1, Math.abs(change) / 2.5);
      const fill = mix(
        change >= 0 ? positiveSoft : negativeSoft,
        change >= 0 ? positive : negative,
        intensity * 0.35,
      );
      layout.rect(x, layout.y, cellWidth, cellHeight, fill);
      layout.textAt(
        x + 6,
        layout.y + 6,
        fitText(shortSectorLabel(String(sector.label ?? "")), cellWidth - 12, 8, "bodyBold"),
        {
          size: 8,
          font: "bodyBold",
          color: charcoal,
        },
      );
      layout.textAt(x + 6, layout.y + 18, formatPct(change), { size: 8, font: "body", color: ink });
    });
    layout.y += cellHeight + 6;
  }
}

function drawSparklines(layout: FlowLayout, report: MarketPulseReport): void {
  const cards = (report.morning_edition?.market_board ?? [])
    .filter((card: Loose) => (card.sparkline ?? []).length >= 2)
    .slice(0, 5);
  if (cards.length === 0) {
    return;
  }
  layout.gap(4);
  layout.subheading("Five-day context");
  const columns = 5;
  const gapX = 7;
  const cellWidth = (width - gapX * (columns - 1)) / columns;
  const cellHeight = 52;
  layout.ensure(cellHeight + 6);
  cards.forEach((card: Loose, index: number) => {
    const x = left + index * (cellWidth + gapX);
    layout.rect(x, layout.y, cellWidth, cellHeight, panelIvory, divider, 0.6);
    layout.textAt(
      x + 7,
      layout.y + 7,
      fitText(String(card.label ?? ""), cellWidth - 14, 8, "body"),
      smallStyle,
    );
    drawSparkline(
      layout,
      card.sparkline as number[],
      card.direction,
      x + 7,
      layout.y + 20,
      cellWidth - 14,
      24,
    );
  });
  layout.y += cellHeight + 6;
}

function drawSparkline(
  layout: FlowLayout,
  values: number[],
  direction: string,
  x: number,
  top: number,
  w: number,
  h: number,
): void {
  const clean = values.filter((value) => Number.isFinite(value));
  if (clean.length < 2) return;
  const min = Math.min(...clean);
  const max = Math.max(...clean);
  const range = max - min || 1;
  const point = (index: number, value: number): [number, number] => [
    x + (index / Math.max(1, clean.length - 1)) * w,
    top + h - ((value - min) / range) * h,
  ];
  const color = direction === "up" ? positive : direction === "down" ? negative : muted;
  for (let index = 1; index < clean.length; index += 1) {
    const [x1, y1] = point(index - 1, clean[index - 1]);
    const [x2, y2] = point(index, clean[index]);
    layout.line(x1, y1, x2, y2, color, 1.4);
  }
  const [lowX, lowY] = point(clean.indexOf(min), min);
  const [highX, highY] = point(clean.indexOf(max), max);
  appendCircle(layout.commands, lowX, pageHeight - lowY, 2, muted, muted);
  appendCircle(layout.commands, highX, pageHeight - highY, 2, gold, gold);
}

function drawOneThing(layout: FlowLayout, copy: PulseBriefCopy): void {
  layout.heading("The One Thing");
  layout.paragraph(copy.one_thing, { size: 10.5, font: "body", color: charcoal, leading: 1.5 }, {
    indent: 12,
    decorate: (top, height) => layout.rect(left, top - 2, 3, height, gold),
  });
}

function drawDeltas(layout: FlowLayout, factPack: PulseBriefFactPack, copy: PulseBriefCopy): void {
  layout.heading(deltaHeading(factPack));
  layout.paragraph(copy.what_changed_summary, bodyStyle);
  layout.gap(8);
  if (!factPack.deltas.baseline && factPack.deltas.vs_yesterday.length > 0) {
    layout.subheading("Changed");
    for (const item of factPack.deltas.vs_yesterday.slice(0, 5)) {
      layout.bullet(item.detail, bodyStyle, item.label);
    }
    layout.gap(6);
    layout.subheading("Unchanged");
  }
  if (factPack.deltas.unchanged.length === 0) {
    layout.paragraph("No unchanged items were material enough to show.", kickerStyle);
    return;
  }
  for (const item of factPack.deltas.unchanged) {
    layout.bullet(item, bodyStyle);
  }
}

function drawYourNames(layout: FlowLayout, factPack: PulseBriefFactPack, copy: PulseBriefCopy): void {
  const rows = factPack.user_names?.rows ?? [];
  if (rows.length === 0) {
    return;
  }
  layout.heading("Your Names", 80);
  if (copy.names_narrative) {
    layout.paragraph(copy.names_narrative, kickerStyle);
    layout.gap(8);
  }
  for (const row of rows) {
    drawNameCard(layout, row);
  }
}

function drawNameCard(layout: FlowLayout, row: PulseBriefUserNameRow): void {
  const tone = directionTone(row.direction);
  const company = [row.companyName, formatNamePriceLine(row)].filter(Boolean).join(" | ");
  const note = row.context?.context_line ?? row.note;
  const innerWidth = width - 20;
  const noteLines = wrapText(note, innerWidth, 9.5, "body");
  const height = 10 + 16 + (company ? 13 : 0) + noteLines.length * 13.5 + 8;
  layout.ensure(height + 8);
  const top = layout.y;
  layout.rect(left, top, width, height, panelIvory, divider, 0.6);
  const color = toneColor(tone);
  appendCircle(layout.commands, left + 14, pageHeight - (top + 16), 3, color, color);
  layout.textAt(left + 24, top + 10, row.ticker, { size: 12, font: "bodyBold", color: charcoal });
  const change = typeof row.changePct === "number" ? formatPct(row.changePct) : "tracked";
  layout.textAt(right - 10, top + 10, change, { size: 10.5, font: "bodyBold", color }, "right");
  let cursor = top + 28;
  if (company) {
    layout.textAt(left + 10, cursor, fitText(company, innerWidth, 8.5, "body"), smallStyle);
    cursor += 13;
  }
  for (const line of noteLines) {
    layout.textAt(left + 10, cursor, line, { size: 9.5, font: "body", color: ink });
    cursor += 13.5;
  }
  layout.y = top + height + 8;
}

function drawCalendarAndHeadlines(
  layout: FlowLayout,
  factPack: PulseBriefFactPack,
  copy: PulseBriefCopy,
): void {
  const calendar = factPack.calendar ?? [];
  const headlines = factPack.headlines ?? [];
  if (calendar.length > 0) {
    layout.heading("Things To Watch");
    if (copy.calendar_narrative) {
      layout.paragraph(copy.calendar_narrative, kickerStyle);
      layout.gap(6);
    }
    calendar.slice(0, 5).forEach((item) => drawCalendarRow(layout, item));
  }
  if (headlines.length > 0) {
    layout.heading("Headlines Worth Knowing");
    if (copy.headlines_narrative) {
      layout.paragraph(copy.headlines_narrative, kickerStyle);
      layout.gap(6);
    }
    headlines.slice(0, 5).forEach((item) => drawHeadlineRow(layout, item));
  }
}

function drawCalendarRow(layout: FlowLayout, item: PulseBriefCalendarItem): void {
  const titleWidth = width - 90 - 60;
  const lines = wrapText(item.title, titleWidth, 10, "bodyBold");
  const height = Math.max(1, lines.length) * 14 + 12;
  layout.ensure(height);
  layout.line(left, layout.y, right, layout.y, divider, 0.5);
  const top = layout.y + 7;
  layout.textAt(left, top + 1, fitText(item.timeLabel ?? "Watch", 84, 8.5, "body"), smallStyle);
  lines.forEach((line, index) => layout.textAt(left + 90, top + index * 14, line, strongStyle));
  layout.textAt(right, top + 1, sanitizeInline(item.impact).toUpperCase(), {
    size: 8,
    font: "bodyBold",
    color: item.impact === "high" ? negative : item.impact === "medium" ? warning : muted,
    tracking: 0.5,
  }, "right");
  layout.y += height;
}

function drawHeadlineRow(layout: FlowLayout, item: PulseBriefHeadline): void {
  const lines = wrapText(item.headline, width, 10, "bodyBold");
  const source = `${item.sourceName}${item.publishedAt ? ` - ${formatDate(item.publishedAt)}` : ""}`;
  const height = lines.length * 14 + 13 + 12;
  layout.ensure(height);
  layout.line(left, layout.y, right, layout.y, divider, 0.5);
  let top = layout.y + 7;
  for (const line of lines) {
    layout.textAt(left, top, line, strongStyle);
    top += 14;
  }
  layout.textAt(left, top, fitText(source, width, 8.5, "body"), smallStyle);
  layout.y += height;
}

function drawSources(layout: FlowLayout, factPack: PulseBriefFactPack): void {
  const sourceText = factPack.sources.length > 0
    ? factPack.sources.join(", ")
    : "No approved sources were attached to this brief.";
  layout.heading("Sources and Method", 30);
  layout.paragraph(`Sources: ${sourceText}.`, smallStyle);
  layout.gap(4);
  layout.paragraph(
    "Method: Thesis uses official and approved free data where available, compares against stored context when present, and omits unsupported inputs.",
    smallStyle,
  );
  if (factPack.omissions.length > 0) {
    layout.gap(4);
    layout.paragraph(
      `Coverage note: ${
        factPack.omissions.map((item) => item.family).join(", ")
      } had limited approved coverage.`,
      smallStyle,
    );
  }
}

function toneColor(tone: PulseTone): PdfRgb {
  return tone === "positive"
    ? positive
    : tone === "negative"
    ? negative
    : tone === "caution"
    ? warning
    : muted;
}

function mix(base: PdfRgb, accent: PdfRgb, amount: number): PdfRgb {
  return [0, 1, 2].map((index) => base[index] + (accent[index] - base[index]) * amount) as PdfRgb;
}

// One-line text clipped with "..." to fit a cell.
function fitText(text: string, maxWidth: number, size: number, font: "body" | "bodyBold"): string {
  const safe = sanitizeInline(text);
  if (estimateTextWidth(safe, size, font) <= maxWidth) {
    return safe;
  }
  let cut = safe;
  while (cut.length > 1 && estimateTextWidth(`${cut}...`, size, font) > maxWidth) {
    cut = cut.slice(0, -1);
  }
  return `${cut.trimEnd()}...`;
}
